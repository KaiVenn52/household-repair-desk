import { test } from 'node:test';
import assert from 'node:assert/strict';
import { once } from 'node:events';
import { request } from 'node:http';
import { Client } from '@modelcontextprotocol/sdk/client/index.js';
import { StreamableHTTPClientTransport } from '@modelcontextprotocol/sdk/client/streamableHttp.js';
import { createApp } from '../src/server.js';
test('official SDK client negotiates 2025-11-25 and executes real HTTP tools', async t => {
  const { app } = createApp({ dataFile: null, clock: () => new Date('2026-10-16T06:00:00Z') });
  const server = app.listen(0, '127.0.0.1'); await once(server, 'listening'); t.after(() => new Promise(r => server.close(r)));
  const url = `http://127.0.0.1:${server.address().port}`;
  const client = new Client({ name: 'household-integration-test', version: '1.0.0' });
  const transport = new StreamableHTTPClientTransport(new URL(`${url}/mcp`));
  await client.connect(transport); t.after(() => client.close());
  assert.equal(transport.protocolVersion, '2025-11-25');
  const list = await client.listTools(); assert.equal(list.tools.length, 8); assert.ok(!list.tools.some(x => /approve|pay|book/.test(x.name)));
  const call = async (name, args) => { const r = await client.callTool({ name, arguments: args }); assert.ok(!r.isError, JSON.stringify(r)); return r.structuredContent; };
  const task = await call('report_repair', { description: 'Kitchen sink is leaking.', member: 'Alex' });
  const compared = await call('compare_quotes', { taskId: task.id });
  const unavailable = await client.callTool({ name: 'propose_repair', arguments: { taskId: task.id, version: compared.task.version, quoteId: 'q-home', slotId: 'mon-am' } }); assert.equal(unavailable.isError, true);
  const proposal = await call('propose_repair', { taskId: task.id, version: compared.task.version, quoteId: 'q-home', slotId: 'mon-pm' }); assert.equal(proposal.status, 'awaiting_approval'); assert.equal(proposal.proposal.token, undefined);
  const cancelled = await call('cancel_repair', { taskId: task.id, version: proposal.version }); assert.equal(cancelled.status, 'cancelled');
  const invalid = await client.callTool({ name: 'get_repair', arguments: { taskId: 'not-a-uuid' } }); assert.equal(invalid.isError, true);
  assert.equal((await fetch(`${url}/mcp`, { method: 'GET' })).status, 405);
  assert.equal((await fetch(`${url}/mcp`, { method: 'POST', headers: { Origin: 'https://evil.example', 'Content-Type': 'application/json' }, body: '{}' })).status, 403);
  const hostStatus = await new Promise((resolve, reject) => { const req = request(`${url}/api/desk`, { headers: { Host: 'evil.example' } }, response => { response.resume(); resolve(response.statusCode); }); req.on('error', reject); req.end(); });
  assert.equal(hostStatus, 403);
  assert.equal((await fetch(`${url}/mcp`, { method: 'POST', headers: { 'Content-Type': 'application/json', 'MCP-Protocol-Version': '2024-11-05' }, body: '{}' })).status, 400);
});
